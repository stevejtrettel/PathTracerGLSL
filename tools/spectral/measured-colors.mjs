// Writes src/components/color/spectra/measured/colors.ts: the measured reflectances of the 24
// ColorChecker patches (BabelColor average) and five CIE illuminants (A, D65, FL2, FL11, LED-B3),
// as interleaved (λ nm, value) pairs, copied from the downloaded source files.
//
//   node tools/spectral/measured-colors.mjs <spectra root>
//
// <spectra root> holds the downloads listed in docs/claude-2026-11-review/spectral-data-sources.md
// (colour-science/json/… and cie/…). The patches are the colour-science extract of
// DATA_BABELCOLOR_AVERAGE (380–730 nm, 10 nm). A and D65 are the CIE 1 nm tables taken at every
// 5 nm from 360 to 830 nm (the renderer's wavelengths): D65's 1 nm values are linear between
// its 5 nm values, so nothing is lost; A's 1 nm values differ from the line between its 5 nm
// values by at most 0.13%. FL2, FL11 and LED-B3 are the CIE 5 nm tables (380–780 nm). Each
// illuminant is checked against colour-science's copy of the same table.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = process.argv[2];
if (root === undefined) throw new Error('usage: node tools/spectral/measured-colors.mjs <spectra root>');
const out = join(dirname(fileURLToPath(import.meta.url)), '../../src/components/color/spectra/measured/colors.ts');

const csv = (file) => readFileSync(join(root, 'cie', file), 'utf8').trim().split(/\r?\n/).map((line) => line.split(','));
const colour = (name) => JSON.parse(readFileSync(join(root, 'colour-science/json', name), 'utf8'));

// Number text as the source wrote it, without trailing zeros.
const text = (s) => String(Number(s));

/** The (λ, value) pairs of a CIE CSV column at λ ∈ [lo, hi] that are multiples of 5 nm. */
function cieColumn(file, column, lo, hi) {
    return csv(file)
        .filter((row) => Number(row[0]) >= lo && Number(row[0]) <= hi && Number(row[0]) % 5 === 0)
        .map((row) => [text(row[0]), text(row[column])]);
}

const illuminantsCS = colour('colorimetry__illuminants__sds__DATA_ILLUMINANTS_CIE.json');
function checkedAgainstColour(name, pairs) {
    const reference = illuminantsCS[name];
    for (const [lambda, value] of pairs) {
        if (lambda in reference && Math.abs(reference[lambda] - Number(value)) > 1e-9) {
            throw new Error(`${name} at ${lambda} nm: CIE ${value}, colour-science ${reference[lambda]}`);
        }
    }
    return pairs;
}

const CIE = 'https://files.cie.co.at/Publications-datasets/';
const illuminants = [
    ['illuminant-A', 'CIE standard illuminant A', `${CIE}CIE_std_illum_A_1nm.csv`, checkedAgainstColour('A', cieColumn('CIE_std_illum_A_1nm.csv', 1, 360, 830))],
    ['illuminant-D65', 'CIE standard illuminant D65', `${CIE}CIE_std_illum_D65.csv`, checkedAgainstColour('D65', cieColumn('CIE_std_illum_D65.csv', 1, 360, 830))],
    ['illuminant-FL2', 'CIE illuminant FL2 (cool white fluorescent)', `${CIE}CIE_illum_FLs.csv, column FL2`, checkedAgainstColour('FL2', cieColumn('CIE_illum_FLs.csv', 2, 380, 780))],
    ['illuminant-FL11', 'CIE illuminant FL11 (narrow-band tri-phosphor fluorescent)', `${CIE}CIE_illum_FLs.csv, column FL11`, checkedAgainstColour('FL11', cieColumn('CIE_illum_FLs.csv', 11, 380, 780))],
    ['illuminant-LED-B3', 'CIE illuminant LED-B3 (phosphor-converted blue LED)', `${CIE}CIE_illum_LEDs.csv, column LED-B3`, checkedAgainstColour('LED-B3', cieColumn('CIE_illum_LEDs.csv', 3, 380, 780))],
];

// Patch names: the BabelColor names in lower case with spaces as hyphens; the neutral patches
// keep their Munsell value (white 9.5 … black 2) and drop the density.
const patches = Object.entries(colour('characterisation__colour_checkers__sds__DATA_BABELCOLOR_AVERAGE.json'))
    .map(([name, sd]) => [
        `colorchecker-${name.replace(/\s*\(.*\)$/, '').replace(/ /g, '-')}`,
        name,
        Object.entries(sd).map(([lambda, value]) => [text(lambda), text(value)]),
    ]);
if (patches.length !== 24) throw new Error(`expected 24 patches, found ${patches.length}`);

const rows = (pairs) => {
    const flat = pairs.flat();
    const lines = [];
    for (let i = 0; i < flat.length; i += 16) lines.push(`        ${flat.slice(i, i + 16).join(', ')},`);
    return lines.join('\n');
};

const body = [
    '// Generated by tools/spectral/measured-colors.mjs from the downloaded source files; do not edit.',
    '// Measured spectra at wavelength λ in nm, as interleaved pairs λ₀, v₀, λ₁, v₁, … with λ increasing.',
    '//',
    '// Reflectances of the 24 ColorChecker Classic patches: the BabelColor average of 30 charts,',
    '// 380–730 nm in 10 nm steps, as published by BabelColor',
    '// (https://www.babelcolor.com/index_htm_files/ColorChecker_RGB_and_spectra.zip) and copied from',
    '// colour-science, DATA_BABELCOLOR_AVERAGE in',
    '// https://github.com/colour-science/colour/blob/9072a98d04e048fe0ea2b1e3aa8429d6e95d37b6/colour/characterisation/datasets/colour_checkers/sds.py',
    '//',
    '// Relative spectral power of CIE illuminants (any overall factor; the measured kind normalizes an',
    '// emission table to unit luminance), from the CIE data tables (https://cie.co.at/data-tables).',
    '',
    'export const reflectanceTables: Readonly<Record<string, readonly number[]>> = {',
    ...patches.flatMap(([name, source, pairs]) => [`    // '${source}', ${pairs.length} knots`, `    '${name}': [`, rows(pairs), '    ],']),
    '};',
    '',
    'export const emissionTables: Readonly<Record<string, readonly number[]>> = {',
    ...illuminants.flatMap(([name, title, url, pairs]) => [`    // ${title}: ${url}, ${pairs.length} knots (${pairs[0][0]}–${pairs[pairs.length - 1][0]} nm)`, `    '${name}': [`, rows(pairs), '    ],']),
    '};',
    '',
].join('\n');
writeFileSync(out, body);
console.log(`wrote ${out}: ${patches.length} reflectances, ${illuminants.length} illuminants`);
