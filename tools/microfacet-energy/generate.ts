// Builds the microfacet energy table (src/components/materials/microfacet_energy/build.ts
// has the math and the layout) and writes data/energy.bin plus data.ts beside it.
//
//   npx vite-node tools/microfacet-energy/generate.ts
//
// The work is split over one child process per CPU (node columns dealt round-robin); each
// child computes its columns and its share of the E_avg values in float64 and returns them as
// JSON. The result does not depend on the split: every node is the same deterministic sum.

import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpus } from 'node:os';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import {
    TABLE_SIZE, TABLE_SLICES, QUADRATURE_N, AVERAGE_NODES,
    conductorAverage, nodeAlpha, nodeColumn, writeColumn,
} from '../../src/components/materials/microfacet_energy/build.js';

const VERSION = 'ggx-smith-energy-v1';
const OUT_DIR = resolve(__dirname, '../../src/components/materials/microfacet_energy');
const ROWS = TABLE_SIZE * TABLE_SLICES;
const COLUMNS = TABLE_SIZE * TABLE_SIZE;

interface Column { enter: number[]; leave: number[] }
interface Part { columns: Record<number, Column>; averages: Record<number, number> }

function computePart(part: number, parts: number): Part {
    const averages: Record<number, number> = {};
    for (let j = part; j < TABLE_SIZE; j += parts) averages[j] = conductorAverage(nodeAlpha(j));
    const columns: Record<number, Column> = {};
    for (let c = part; c < COLUMNS; c += parts) {
        const { enter, leave } = nodeColumn(c % TABLE_SIZE, Math.floor(c / TABLE_SIZE));
        columns[c] = { enter: Array.from(enter), leave: Array.from(leave) };
    }
    return { columns, averages };
}

async function main() {
    const part = process.env.ENERGY_PART;
    if (part !== undefined) {
        const result = computePart(Number(part), Number(process.env.ENERGY_PARTS));
        writeFileSync(process.env.ENERGY_OUT!, JSON.stringify(result));
        return;
    }

    const parts = cpus().length;
    const tmp = join(OUT_DIR, '.parts');
    mkdirSync(tmp, { recursive: true });
    const started = Date.now();
    const files = await Promise.all(Array.from({ length: parts }, (_, p) => new Promise<string>((done, fail) => {
        const out = join(tmp, `part-${p}.json`);
        const child = spawn(process.execPath, [resolve(__dirname, '../../node_modules/vite-node/vite-node.mjs'), __filename], {
            env: { ...process.env, ENERGY_PART: String(p), ENERGY_PARTS: String(parts), ENERGY_OUT: out },
            stdio: 'inherit',
        });
        child.on('exit', (code) => (code === 0 ? done(out) : fail(new Error(`part ${p} exited with ${code}`))));
    })));

    const results = files.map((file) => JSON.parse(readFileSync(file, 'utf8')) as Part);
    rmSync(tmp, { recursive: true });
    const averages = new Float64Array(TABLE_SIZE);
    for (const result of results) for (const [j, value] of Object.entries(result.averages)) averages[Number(j)] = value;
    const data = new Float32Array(TABLE_SIZE * ROWS * 4);
    for (const result of results) {
        for (const [c, column] of Object.entries(result.columns)) {
            const i = Number(c) % TABLE_SIZE, j = Math.floor(Number(c) / TABLE_SIZE);
            writeColumn(data, i, j, { enter: Float64Array.from(column.enter), leave: Float64Array.from(column.leave) }, averages[j]);
        }
    }

    const bytes = Buffer.from(data.buffer);
    mkdirSync(join(OUT_DIR, 'data'), { recursive: true });
    writeFileSync(join(OUT_DIR, 'data', 'energy.bin'), bytes);
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const meta = { version: VERSION, width: TABLE_SIZE, height: ROWS, quadratureN: QUADRATURE_N, averageNodes: AVERAGE_NODES, sha256 };
    writeFileSync(join(OUT_DIR, 'data.ts'),
        `// Generated by tools/microfacet-energy/generate.ts; the layout is in build.ts.\n`
        + `export const microfacetEnergyData = ${JSON.stringify(meta, null, 4)};\n`);
    console.log(`energy table ${TABLE_SIZE}×${ROWS} written in ${((Date.now() - started) / 1000).toFixed(0)} s on ${parts} processes, sha256 ${sha256}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
