// The support table: which ambient space each occupant and each descriptor-less feature is
// implemented in, printed from the registries and SPACE_LIMITATIONS into
// src/components/ambient/support.md. A stale file fails this test; `npx vitest run -u`
// rewrites it.

import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { AMBIENT_SPACES } from '../../src/components/ambient/index.js';
import { spacesOf, type SpaceBodies, type SpaceList } from '../../src/components/descriptors.js';
import { PRIMITIVES } from '../../src/components/geometry/index.js';
import { LIGHT_KINDS, LIGHT_SELECTIONS } from '../../src/components/lights/index.js';
import { MATERIAL_MODELS } from '../../src/components/materials/index.js';
import { VOLUME_SCATTERING_MODELS } from '../../src/components/volume_scattering/index.js';
import { CAMERA_MODELS } from '../../src/components/camera/index.js';
import { ENV_CHARTS } from '../../src/components/env/index.js';
import { AOVS } from '../../src/components/aov/index.js';
import { MESH_TRAVERSALS, INSTANCE_ACCELS, OBJECT_DISPATCHES } from '../../src/components/intersection/index.js';
import { SPACE_LIMITATIONS } from '../../src/compiler/analyze/curved.js';

/** The families whose occupants carry GLSL keyed by space. */
const FAMILIES: Record<string, Record<string, { glsl: SpaceBodies; local?: boolean } | undefined>> = {
    geometry: PRIMITIVES, lights: LIGHT_KINDS, materials: MATERIAL_MODELS, volume_scattering: VOLUME_SCATTERING_MODELS,
    camera: CAMERA_MODELS, 'env chart': ENV_CHARTS, aov: AOVS,
};

function supportTable(): string {
    const spaces = Object.keys(AMBIENT_SPACES);
    const row = (family: string, name: string, has: readonly string[]) =>
        `| ${family} | ${name} | ${spaces.map((s) => (has.includes(s) ? 'yes' : '—')).join(' | ')} |`;
    const bodies = (family: string, registry: Record<string, { glsl: SpaceBodies; local?: boolean } | undefined>) =>
        Object.entries(registry)
            .filter(([, d]) => d !== undefined && d.local !== true)
            .map(([key, d]) => row(family, key, spacesOf(d!.glsl)));
    const listed = (family: string, registry: Record<string, { spaces: SpaceList }>) =>
        Object.entries(registry).map(([key, d]) => row(family, key, d.spaces));
    const header = [`| family | occupant or feature | ${spaces.join(' | ')} |`, `|---|---|${spaces.map(() => '---|').join('')}`];
    return [
        '# Space support',
        '',
        'Generated by tests/components/spaceSupport.test.ts from the registries and from',
        'SPACE_LIMITATIONS (src/compiler/analyze/curved.ts); `npx vitest run -u` rewrites it.',
        '',
        'An occupant with GLSL supports a space exactly when it has a body for it; an estimator',
        'occupant emitted from TypeScript lists its spaces; a feature without a descriptor is a',
        'limitation row. Shared files without a descriptor (ray.glsl, the shadow walkers,',
        'microfacet.glsl) are not listed: the witnesses of each space establish them. Film-side',
        'families (pixel, sampler, sensor, color, accumulator, tonemap) never see a point and are',
        'not keyed by space.',
        '',
        ...header,
        ...Object.entries(FAMILIES).flatMap(([family, registry]) => bodies(family, registry)),
        ...listed('light selection', LIGHT_SELECTIONS),
        ...listed('mesh traversal', MESH_TRAVERSALS),
        ...listed('instance traversal', INSTANCE_ACCELS),
        ...listed('object dispatch', OBJECT_DISPATCHES),
        ...SPACE_LIMITATIONS.map((l) => row('limitation', l.feature, l.spaces)),
        '',
    ].join('\n');
}

describe('space bodies', () => {
    // Every occupant runs somewhere: the body contract tests (tests/helpers/spaceBodies.ts)
    // check every body an occupant has, which proves nothing for an occupant with none.
    it('every occupant has at least one body, and every estimator occupant at least one space', () => {
        const bodiless = Object.entries(FAMILIES).flatMap(([family, registry]) => Object.entries(registry)
            .filter(([, d]) => d !== undefined && spacesOf(d.glsl).length === 0)
            .map(([key]) => `${family} '${key}'`));
        const listedRegistries: Record<string, Record<string, { spaces: SpaceList }>> = {
            'light selection': LIGHT_SELECTIONS, 'mesh traversal': MESH_TRAVERSALS,
            'instance traversal': INSTANCE_ACCELS, 'object dispatch': OBJECT_DISPATCHES,
        };
        const spaceless = Object.entries(listedRegistries).flatMap(([family, registry]) => Object.entries(registry)
            .filter(([, d]) => d.spaces.length === 0)
            .map(([key]) => `${family} '${key}'`));
        expect([...bodiless, ...spaceless]).toEqual([]);
    });

    // A body travels with its origin (one file may be listed under several spaces), so the
    // origin must name the file the source came from: source maps and the digest report it.
    for (const [family, registry] of Object.entries(FAMILIES)) {
        for (const [key, d] of Object.entries(registry)) {
            if (d === undefined || d.local === true) continue;
            for (const [space, body] of Object.entries(d.glsl)) {
                it(`${family} '${key}' (${space}): the origin names the file the source came from`, () => {
                    expect(readFileSync(resolve(__dirname, '../../src', body!.origin), 'utf8')).toBe(body!.source);
                });
            }
        }
    }
});

describe('space support table', () => {
    it('matches src/components/ambient/support.md', async () => {
        await expect(supportTable()).toMatchFileSnapshot('../../src/components/ambient/support.md');
    });
});
